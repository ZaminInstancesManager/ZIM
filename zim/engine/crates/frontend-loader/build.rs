//! Build script: embed the default frontend package into the crate.
//!
//! The default frontend lives at the repo's `zim/frontend/` (outside
//! the engine tree, per `docs/api/FRONTEND_EXTENSION_SPEC.md` §5).
//! This script whitelists exactly the package payload — the
//! manifest, `pages/`, and `assets/` (the compiled TS output) — and
//! emits a static file table the loader serves from memory. Sources
//! (`src/`), tooling (`package.json`, `tsconfig.json`), and
//! `node_modules` are deliberately not embedded.
//!
//! The whitelist keeps the embedded package equal to what a custom
//! package would contain, and keeps the engine binary free of
//! development files.

use std::env;
use std::fs;
use std::path::PathBuf;

/// Package-root-relative prefixes that are embedded.
const EMBED_PREFIXES: &[&str] = &["pages/", "assets/"];

/// The manifest's package-root-relative path.
const MANIFEST_PATH: &str = "zim.frontend.json";

fn main() {
    println!("cargo:rerun-if-changed=../../../frontend");
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let frontend_dir = manifest_dir
        .join("../../../frontend")
        .canonicalize()
        .expect("the repo's zim/frontend/ directory must exist next to the engine tree");

    // Deterministic order: sorted relative paths.
    let mut files: Vec<(String, PathBuf)> = Vec::new();
    collect_files(&frontend_dir, &frontend_dir, &mut files);
    files.sort_by(|a, b| a.0.cmp(&b.0));

    let manifest_abs = frontend_dir.join(MANIFEST_PATH);
    assert!(
        manifest_abs.exists(),
        "the default frontend manifest is missing: {}",
        manifest_abs.display()
    );

    let mut out = String::new();
    out.push_str("// @generated by build.rs — the embedded default frontend package.\n");
    out.push_str("// Do not edit; the source of truth is `zim/frontend/` at the repo root.\n\n");
    out.push_str("/// (package-root-relative path, file bytes) pairs, sorted by path.\n");
    out.push_str("pub static FILES: &[(&str, &[u8])] = &[\n");
    out.push_str(&entry(MANIFEST_PATH, &manifest_abs));
    for (relative, absolute) in &files {
        if EMBED_PREFIXES.iter().any(|p| relative.starts_with(p)) {
            out.push_str(&entry(relative, absolute));
        }
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("default_package.rs"), out)
        .expect("writing the generated default-package table");
}

/// One table entry (absolute include path — stable regardless of
/// where the build runs from).
fn entry(relative: &str, absolute: &std::path::Path) -> String {
    format!(
        "    ({:?}, include_bytes!({:?})),\n",
        relative,
        absolute.to_string_lossy()
    )
}

/// Recursively collect files under `root`, tracking root-relative
/// (forward-slash) paths.
fn collect_files(root: &std::path::Path, dir: &std::path::Path, out: &mut Vec<(String, PathBuf)>) {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(_) => return,
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            // Development tooling is never part of the payload.
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if name == "node_modules" || name.starts_with('.') {
                continue;
            }
            collect_files(root, &path, out);
        } else {
            let relative = path
                .strip_prefix(root)
                .expect("collected path is under root")
                .to_string_lossy()
                .replace('\\', "/");
            out.push((relative, path));
        }
    }
}
