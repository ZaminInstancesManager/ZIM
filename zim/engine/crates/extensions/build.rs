//! Build script: embed the bundled default addon packages into the
//! crate.
//!
//! The bundled default addons (spec §6) live at the repo's
//! `zim/extensions/` — every `org.zaminmc.extension.*` directory
//! directly under it. This script whitelists each package's payload
//! (the `zim.addon.json` manifest, `pages/`, `assets/`) and emits a
//! static table the loader seeds data directories from. Sample
//! addons (`zim/extensions/samples/`) and sources are deliberately
//! not embedded.
//!
//! The whitelist keeps the embedded packages equal to what an
//! uploaded package would contain, and keeps the engine binary free
//! of development files.

use std::env;
use std::fs;
use std::path::PathBuf;

/// Package-root-relative prefixes that are embedded.
const EMBED_PREFIXES: &[&str] = &["pages/", "assets/"];

/// The manifest's package-root-relative path.
const MANIFEST_PATH: &str = "zim.addon.json";

/// Only directories with this prefix are bundled defaults (§6).
const BUNDLED_PREFIX: &str = "org.zaminmc.extension.";

fn main() {
    println!("cargo:rerun-if-changed=../../../extensions");
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let extensions_dir = manifest_dir
        .join("../../../extensions")
        .canonicalize()
        .expect("the repo's zim/extensions/ directory must exist next to the engine tree");

    // Deterministic order: addon id, then relative path.
    let mut rows: Vec<(String, String, PathBuf)> = Vec::new();
    let mut bundled: Vec<String> = Vec::new();
    let entries = fs::read_dir(&extensions_dir).expect("reading zim/extensions/");
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        if !name.starts_with(BUNDLED_PREFIX) || !entry.path().is_dir() {
            continue;
        }
        bundled.push(name.clone());
        let mut files: Vec<(String, PathBuf)> = Vec::new();
        collect_files(&entry.path(), &entry.path(), &mut files);
        files.sort_by(|a, b| a.0.cmp(&b.0));
        let manifest_abs = entry.path().join(MANIFEST_PATH);
        assert!(
            manifest_abs.exists(),
            "the bundled addon {name} is missing its {MANIFEST_PATH}"
        );
        rows.push((name.clone(), MANIFEST_PATH.to_owned(), manifest_abs));
        for (relative, absolute) in files {
            if EMBED_PREFIXES.iter().any(|p| relative.starts_with(p)) {
                rows.push((name.clone(), relative, absolute));
            }
        }
    }
    bundled.sort();
    rows.sort_by(|a, b| (&a.0, &a.1).cmp(&(&b.0, &b.1)));

    let mut out = String::new();
    out.push_str("// @generated by build.rs — the embedded bundled default addons.\n");
    out.push_str("// Do not edit; the source of truth is `zim/extensions/` at the repo root.\n\n");
    out.push_str("/// (addon id, package-root-relative path, file bytes) rows, sorted.\n");
    out.push_str("pub static FILES: &[(&str, &str, &[u8])] = &[\n");
    for (addon, relative, absolute) in &rows {
        out.push_str(&entry(addon, relative, absolute));
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("bundled_addons.rs"), out)
        .expect("writing the generated bundled-addons table");
}

fn entry(addon: &str, relative: &str, absolute: &PathBuf) -> String {
    let bytes = fs::read(absolute).expect("reading an embedded addon file");
    format!("    ({:?}, {:?}, &{:?}),\n", addon, relative, bytes)
}

fn collect_files(root: &PathBuf, dir: &PathBuf, out: &mut Vec<(String, PathBuf)>) {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(_) => return,
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_files(root, &path, out);
        } else {
            let relative = path
                .strip_prefix(root)
                .expect("the walk stays under the package root")
                .to_string_lossy()
                .replace('\\', "/");
            out.push((relative, path));
        }
    }
}
